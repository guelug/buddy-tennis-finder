const DICTIONARIES: Record<LanguageCode, Dictionary> = { es, en };

const storageKey = "matchpoint-language";

type I18nContextValue = {
  lang: LanguageCode;
  setLang: (lang: LanguageCode) => void;
  t: (key: string) => string;
};

const I18nContext = React.createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: React.PropsWithChildren) {
  const [lang, setLangState] = React.useState<LanguageCode>("es");

  React.useEffect(() => {
    let active = true;
    const restore = async () => {
      try {
        const stored = Platform.OS === "web" && typeof window !== "undefined"
          ? window.localStorage.getItem(storageKey)
          : await AsyncStorage.getItem(storageKey);
        if (active && (stored === "es" || stored === "en")) setLangState(stored);
      } catch {
        // Sin storage disponible: conservamos el idioma por defecto.
      }
    };
    void restore();
    return () => { active = false; };
  }, []);

  const setLang = React.useCallback((next: LanguageCode) => {
    setLangState(next);
    if (Platform.OS === "web" && typeof window !== "undefined") {
      try {
        window.localStorage.setItem(storageKey, next);
      } catch {
        // Navegadores con storage bloqueado: conservamos el idioma durante la sesión.
      }
    } else {
      void AsyncStorage.setItem(storageKey, next).catch(() => {});
    }
  }, []);

  const t = React.useCallback(
    (key: string) => DICTIONARIES[lang][key] ?? DICTIONARIES.es[key] ?? key,
    [lang]
  );

  const value = React.useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = React.useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n debe usarse dentro de I18nProvider");
  }
  return value;
}
